export type PackageCategory = 'evening' | 'combo' | 'short' | 'selfdrive' | 'vip' | 'city';
export type PriceUnit = 'person' | 'vehicle' | 'group' | '2 adults' | 'hour';

export interface SafariPackage {
  id: string;
  slug: string;
  category: PackageCategory;
  tier: string;
  title: string;
  tagline: string;
  price: number;
  originalPrice: number;
  priceUnit: PriceUnit;
  duration: string;
  location: string;
  pickupInfo: string;
  /** 0 = no verified reviews yet; UI and schema hide ratings in that case. */
  rating: number;
  reviewsCount: number;
  badge?: string;
  isPopular?: boolean;
  /** Photo path. City tours without a real photo yet render an illustrated card instead. */
  image?: string;
  /** Full promotional poster, shown uncropped on the detail page. */
  poster?: string;
  includes: string[];
  excludes?: string[];
  itinerary?: { time: string; title: string; desc: string }[];
  /** Show the whole main photo over a blurred copy, for tall photos that no crop can fit. */
  imageContain?: boolean;
  /** Photos for the detail page strip; packages without their own use the default camp photos. */
  gallery?: { src: string; label: string }[];
  /** One clear line on what the price covers (per person vs per car, shared vs private). */
  priceNote?: string;
  whatsAppText: string;
  detailPath: string;
}

